# hooks.sh - the C option's implementation of the shared gates.sh hook contract (TOOL-01 spike). Sourced, never executed.
# The caller (gates.sh or a bench script) sets SPIKE_DIR (spikes/tool-01) and OPT_DIR (spikes/tool-01/c) first.
# Build trees live under SPIKE_DIR/out/, which is gitignored.

c_build_type() {
  case $1 in
    debug) echo Debug ;;
    release) echo Release ;;
    *) echo "hooks: unknown profile $1" >&2; return 1 ;;
  esac
}

# opt_build <debug|release>: configure when needed, then build everything (library and runner).
opt_build() {
  _p=${1:?profile}
  _t=$(c_build_type "$_p") || return 1
  _bd=$SPIKE_DIR/out/build-c-$_p
  _log=$SPIKE_DIR/out/build-c-$_p.log
  mkdir -p "$SPIKE_DIR/out" || return 1
  : > "$_log"
  if [ ! -f "$_bd/CMakeCache.txt" ]; then
    cmake -S "$OPT_DIR" -B "$_bd" -G Ninja "-DCMAKE_BUILD_TYPE=$_t" >> "$_log" 2>&1 || { cat "$_log" >&2; return 1; }
  fi
  cmake --build "$_bd" >> "$_log" 2>&1 || { cat "$_log" >&2; return 1; }
}

# opt_runner [debug|release]: print the path of the manifest runner binary for that profile (default debug).
opt_runner() {
  _p=${1:-debug}
  c_build_type "$_p" > /dev/null || return 1
  echo "$SPIKE_DIR/out/build-c-$_p/duospool-runner"
}

# opt_install <src_copy> <build_dir> <prefix> <remap yes|no>
# Builds the library from the given source copy and installs lib/libduospool.a, include/duospool.h and
# lib/pkgconfig/duospool.pc under prefix. With remap yes the compile gets -ffile-prefix-map / -fdebug-prefix-map for both
# spellings of the copy and build paths (macOS /var is a symlink to /private/var, Pitfall 12); with remap no it does not
# (the seeded-leak control).
opt_install() {
  _src=${1:?src_copy}
  _bd=${2:?build_dir}
  _prefix=${3:?prefix}
  _remap=${4:?remap}
  mkdir -p "$_bd" "$_prefix" || return 1
  _srcp=$(cd "$_src" && pwd -P) || return 1
  _bdp=$(cd "$_bd" && pwd -P) || return 1
  # RelWithDebInfo is a debug-info build type on purpose: with it the installed archive carries DWARF paths, so the
  # path-leak grep inspects an archive that can leak. A plain Release archive would pass the grep vacuously.
  set -- "-DCMAKE_BUILD_TYPE=RelWithDebInfo"
  if [ "$_remap" = yes ]; then
    set -- "$@" "-DCMAKE_C_FLAGS=-ffile-prefix-map=$_src=/src -ffile-prefix-map=$_srcp=/src -ffile-prefix-map=$_bd=/build -ffile-prefix-map=$_bdp=/build -fdebug-prefix-map=$_src=/src -fdebug-prefix-map=$_srcp=/src -fdebug-prefix-map=$_bd=/build -fdebug-prefix-map=$_bdp=/build"
  fi
  _ilog=$_bd.install.log
  {
    cmake -S "$_src" -B "$_bd" -G Ninja "$@" &&
      cmake --build "$_bd" --target duospool &&
      cmake --install "$_bd" --prefix "$_prefix"
  } > "$_ilog" 2>&1 || { cat "$_ilog" >&2; return 1; }
  if ! grep -qx 'INSTALL-BUILD-TYPE c RelWithDebInfo' "$SPIKE_DIR/LOG.md" 2> /dev/null; then
    echo 'INSTALL-BUILD-TYPE c RelWithDebInfo' >> "$SPIKE_DIR/LOG.md"
  fi
}

# opt_fuzz60 <seconds> <planted yes|no> (protocol G5, D-35 recipe)
# Apple clang -fsanitize=fuzzer-no-link,address; the libFuzzer runtime archive from Homebrew llvm@21 is linked by explicit
# path, so llvm@21 is never on PATH (D-17). Binaries, the seed corpus and crash artifacts live under SPIKE_DIR/out/.
# Prints  FUZZ elapsed=<s> crashed=<yes|no> execs_per_sec=<n>  and returns 0 when the outcome is the wanted one
# (planted yes: a crash was found; planted no: no crash), 1 otherwise.
FUZZ_RT=/opt/homebrew/opt/llvm@21/lib/clang/21/lib/darwin/libclang_rt.fuzzer_osx.a

opt_fuzz60() {
  _secs=${1:?seconds}
  _pl=${2:?planted}
  case $_pl in yes | no) ;; *) echo "hooks: planted must be yes or no" >&2; return 1 ;; esac
  _fd=$SPIKE_DIR/out/fuzz-c-$_pl
  rm -rf "$_fd"
  mkdir -p "$_fd/corpus" "$_fd/artifacts" || return 1
  _def=
  if [ "$_pl" = yes ]; then _def=-DDS_PLANTED_BUG; fi
  if [ ! -f "$FUZZ_RT" ]; then
    echo "hooks: libFuzzer runtime archive not found at $FUZZ_RT" >&2
    return 1
  fi
  # shellcheck disable=SC2086
  /usr/bin/clang -std=c11 -g -O1 -fsanitize=fuzzer-no-link,address $_def -I "$OPT_DIR/include" \
    "$OPT_DIR/src/core.c" "$OPT_DIR/fuzz/fuzz_loader.c" -fsanitize=address "$FUZZ_RT" -lc++ \
    -o "$_fd/fuzz_loader" > "$_fd/build.log" 2>&1 || { cat "$_fd/build.log" >&2; return 1; }
  # One generated all-zero 64 KiB seed so the clean run also exercises the accepted-load path (generated bytes stay in out/).
  head -c 65536 /dev/zero > "$_fd/corpus/seed-zero" || return 1
  _t0=$(perl -MTime::HiRes=time -e 'printf "%.3f", time')
  _hard=$((_secs + 60))
  # handle_sigtrap=1: __builtin_trap raises SIGTRAP on arm64, which the ASan runtime ignores by default, so without it the
  # process would die with no libFuzzer report and no crash artifact.
  ( ASAN_OPTIONS=handle_sigtrap=1 perl -e 'alarm shift; exec @ARGV' "$_hard" "$_fd/fuzz_loader" -max_total_time="$_secs" -max_len=1048600 \
    "-artifact_prefix=$_fd/artifacts/" "$_fd/corpus" > "$_fd/run.log" 2>&1 ) 2> /dev/null && _rc=0 || _rc=$?
  _t1=$(perl -MTime::HiRes=time -e 'printf "%.3f", time')
  _el=$(awk -v a="$_t0" -v b="$_t1" 'BEGIN { printf "%.1f", b - a }')
  _eps=$(awk '{ for (i = 1; i < NF; i++) if ($i == "exec/s:") v = $(i + 1) } END { print (v == "" ? 0 : v) }' "$_fd/run.log")
  _crashed=no
  if [ "$_rc" -ne 0 ]; then _crashed=yes; fi
  echo "FUZZ elapsed=$_el crashed=$_crashed execs_per_sec=$_eps"
  if [ "$_pl" = yes ]; then
    [ "$_crashed" = yes ] && grep -q 'ERROR: \(libFuzzer\|AddressSanitizer\)' "$_fd/run.log"
  else
    [ "$_crashed" = no ]
  fi
}
